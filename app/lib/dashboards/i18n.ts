// French name for a data value; categories are "Colour · Region"
export function term(lang: Lang, value: string): string {
  if (lang === "en") return value;
  if (WORDS[value]) return WORDS[value];
  if (value.startsWith("Agency ")) return "Agence " + value.slice(7);
  if (value.includes(" · ")) return value.split(" · ").map((p) => term(lang, p)).join(" · ");
  return value;
}
